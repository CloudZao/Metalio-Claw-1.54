// ---------------------------------------------------------------------------
// ThemeScreen
//
// 主题选择 App。布局（240x240）：
//
//   ┌──────────────────────────────┐
//   │           主题                │  ← header
//   ├──────────────────────────────┤
//   │   ┌────┐      ┌────┐        │
//   │   │ T1 │      │ T2 │  页 0   │  ← 横向翻页，一页 2 卡
//   │   └────┘      └────┘        │
//   │   主题 1       主题 2         │
//   │           ● ○                │  ← 底部分页圆点
//   └──────────────────────────────┘
//
// 交互：
//   - 左右滑切换页（主题 1/2 | 3/4）
//   - 点击非当前主题 -> 立即 SetCurrentThemeId 并重建本页
//   - 点击当前主题 -> no-op
//   - 右滑返回 -> 回设置页 / 主页
// ---------------------------------------------------------------------------
class ThemeScreen {
public:
    static lv_obj_t* Create();
    static void LifecycleCallback(screen_lifecycle_event_t event);
};
